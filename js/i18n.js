  let currentLang = "es";
  
  function t(key) {
    return translations[currentLang][key] || key;
  }
  
  function getLang() {
    return currentLang;
  }
  
  function setLang(lang) {
    if (lang === "es" || lang === "en") {
      currentLang = lang;
      localStorage.setItem("dky-lang", currentLang);
      updateUI();
    }
  }
  
  function updateUI() {
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (key && translations[currentLang][key]) {
        el.textContent = t(key);
      }
    });
    document.documentElement.lang = currentLang;
    document.title = currentLang === "es" ? "DKY Jewelry — Oro Fino" : "DKY Jewelry — Fine Gold";
    
    const langIndicator = document.getElementById("lang-indicator");
    if (langIndicator) langIndicator.textContent = currentLang.toUpperCase();
    
    window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: currentLang } }));
  }
  
  function init() {
    const saved = localStorage.getItem("dky-lang");
    if (saved === "es" || saved === "en") currentLang = saved;
    updateUI();
    
    const langToggle = document.getElementById("lang-toggle");
    if (langToggle) langToggle.addEventListener("click", () => setLang(currentLang === "es" ? "en" : "es"));
  }
  
  return { init, t, getLang, setLang };
